// CATEGORY TRANSLATION HELPER
// ============================================================

export const translateCategory = (catName, t) => {
  if (!catName) return "";

  const keyMap = {
    all: "cat_all",
    beauty: "cat_beauty",
    electronics: "cat_electronics",
    bags: "cat_bags",
    shoes: "cat_shoes",
    fashion: "cat_fashion",
    accessories: "cat_accessories",
    gifts: "cat_gifts",
    college: "cat_college",
    school: "cat_school",
    travel: "cat_travel",
    home: "cat_home",
    timepieces: "cat_timepieces",
    tech: "cat_tech"
  };

  const key = keyMap[catName.toLowerCase().trim()];

  if (key && t) {
    const translated = t(key);

    if (translated && translated !== key) {
      return translated;
    }
  }

  return catName;
};
